#include "test_util.h"

namespace crate::test {

std::string makeBundle (const TempDir& dir, const std::string& bundleName, const std::string& cid,
                        const std::string& name, const std::string& vendor,
                        const std::vector<std::string>& subCategories, bool withSnapshot)
{
	auto bundle = dir.mkdir (bundleName);
	auto resources = dir.mkdir (bundleName + "/Contents/Resources");
	std::string subs;
	for (size_t i = 0; i < subCategories.size (); ++i)
	{
		if (i)
			subs += ", ";
		subs += "\"" + subCategories[i] + "\"";
	}
	std::string snapshotJson;
	if (withSnapshot)
		snapshotJson = R"(,
			"Snapshots": [ { "Scale Factor": 1.0, "Path": "Snapshots/)" + cid + R"(_snapshot.png" } ])";
	std::string json = R"({
		// generated by the Crate test fixture helper
		"Name": ")" + name + R"(",
		"Version": "1.0.0",
		"Factory Info": { "Vendor": ")" + vendor + R"(" },
		"Classes": [ {
			"CID": ")" + cid + R"(",
			"Category": "Audio Module Class",
			"Name": ")" + name + R"(",
			"Vendor": ")" + vendor + R"(",
			"Version": "1.0.0",
			"SDKVersion": "VST 3.7.5",
			"Sub Categories": [ )" + subs + R"( ],
			"Class Flags": 0,
			"Cardinality": 2147483647)" + snapshotJson + R"(
		} ]
	})";
	dir.write (bundleName + "/Contents/Resources/moduleinfo.json", json);
	if (withSnapshot)
	{
		// 1x1 transparent PNG, enough for a real decode in the UI layer.
		static const unsigned char png[] = {
		    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
		    0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
		    0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
		    0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
		    0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49,
		    0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82};
		auto path = fs::join (resources, "Snapshots/" + cid + "_snapshot.png");
		fs::writeFile (path, png, sizeof (png));
	}
	return bundle;
}

} // namespace crate::test
